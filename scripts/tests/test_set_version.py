"""scripts/set-version.py: every version site of the repository moves together,
and nothing else does."""
from pathlib import Path
import json
import runpy
import shutil
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = runpy.run_path(str(ROOT / "scripts/set-version.py"))
BUMP = SCRIPT["bump"]
REFUSED = SCRIPT["Refused"]
WORKSPACE_VERSION = SCRIPT["workspace_version"]


def lock(*packages):
    """A Cargo.lock: (name, version, registry?) per package."""
    text = "# This file is automatically @generated by Cargo.\nversion = 4\n"
    for name, version, registry in packages:
        text += f'\n[[package]]\nname = "{name}"\nversion = "{version}"\n'
        if registry:
            text += 'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
    return text


def json_text(value):
    return json.dumps(value, indent=2) + "\n"


class SetVersionTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.tree("0.5.0")

    def write(self, relative, text):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    def tree(self, version):
        """A small repository with every kind of site at `version`, and a
        registry package that happens to have the same version."""
        self.write("Cargo.toml", f'[workspace]\nmembers = ["crates/*"]\n\n[workspace.package]\nversion = "{version}"\n\n'
                                 '[workspace.dependencies]\nanyhow = { version = "1" }\n')
        for name in ("kronik", "kronik-core"):
            self.write(f"crates/{name}/Cargo.toml", f'[package]\nname = "{name}"\nversion.workspace = true\n')
        self.write("Cargo.lock", lock(("anyhow", version, True), ("kronik", version, False),
                                      ("kronik-core", version, False)))
        self.write("sdk/rust/Cargo.toml", f'[package]\nname = "kronik-sdk"\nversion = "{version}"\n')
        self.write("examples/Cargo.toml", '[workspace]\nmembers = ["kronik-sdk", "counter-rs"]\n\n'
                                          f'[workspace.package]\nversion = "{version}"\n')
        (self.root / "examples/kronik-sdk").symlink_to("../sdk/rust")
        self.write("examples/counter-rs/Cargo.toml", '[package]\nname = "counter-rs"\nversion.workspace = true\n')
        self.write("examples/Cargo.lock", lock(("counter-rs", version, False), ("kronik-sdk", version, False),
                                               ("wit-bindgen", version, True)))
        for example in SCRIPT["STANDALONE"]:
            self.write(f"examples/{example}/Cargo.toml", f'[package]\nname = "{example}"\nversion = "{version}"\n\n'
                                                         '[dependencies]\nserde = { version = "1" }\n')
            self.write(f"examples/{example}/Cargo.lock", lock((example, version, False), ("serde", "1.0.0", True)))
        self.write("sdk/ts/package.json", json_text({"name": "@kronik/sdk", "version": version}))
        self.write("sdk/ts/package-lock.json", json_text({
            "name": "@kronik/sdk", "version": version, "lockfileVersion": 3,
            "packages": {"": {"name": "@kronik/sdk", "version": version},
                         "node_modules/other": {"version": version}}}))
        self.write("examples/package-lock.json", json_text({
            "name": "kronik-examples", "lockfileVersion": 3,
            "packages": {"": {"name": "kronik-examples"}, "../sdk/ts": {"name": "@kronik/sdk", "version": version},
                         "node_modules/other": {"version": version}}}))
        self.write("docs/design/m1-core.md", f'| `GET /v1/health` | | `{{"status":"ok","version":"{version}"}}` |\n')
        self.write("docs/reference/openapi.json", json_text({"openapi": "3.1.0", "info": {"version": version},
                                                             "components": {"example": {"version": version}}}))

    def snapshot(self):
        return {path.relative_to(self.root).as_posix(): path.read_text()
                for path in sorted(self.root.rglob("*")) if path.is_file() and not path.is_symlink()}

    def test_every_site_moves_and_nothing_else(self):
        before = self.snapshot()
        BUMP(self.root, "0.5.0", "0.6.0-dev")
        after = self.snapshot()
        for relative, text in before.items():
            self.assertEqual(text.count('"0.5.0"') - after[relative].count('"0.5.0"'),
                             after[relative].count('"0.6.0-dev"'), relative)
        self.assertEqual(WORKSPACE_VERSION(self.root), "0.6.0-dev")
        # A registry package, an npm dependency and an unrelated schema
        # field at the old version keep it.
        self.assertIn('name = "anyhow"\nversion = "0.5.0"', after["Cargo.lock"])
        self.assertIn('name = "wit-bindgen"\nversion = "0.5.0"', after["examples/Cargo.lock"])
        package_lock = json.loads(after["sdk/ts/package-lock.json"])
        self.assertEqual(package_lock["version"], "0.6.0-dev")
        self.assertEqual(package_lock["packages"][""]["version"], "0.6.0-dev")
        self.assertEqual(package_lock["packages"]["node_modules/other"]["version"], "0.5.0")
        openapi = json.loads(after["docs/reference/openapi.json"])
        self.assertEqual((openapi["info"]["version"], openapi["components"]["example"]["version"]),
                         ("0.6.0-dev", "0.5.0"))
        self.assertIn('"version":"0.6.0-dev"', after["docs/design/m1-core.md"])
        # A second run changes nothing, and every site now agrees.
        BUMP(self.root, "0.5.0", "0.6.0-dev")
        self.assertEqual(self.snapshot(), after)
        BUMP(self.root, "0.6.0-dev", "0.6.0-dev", write=False)

    def test_a_site_at_another_version_is_refused_before_anything_changes(self):
        self.write("examples/foreign-pg/Cargo.toml", '[package]\nname = "foreign-pg"\nversion = "0.4.1-dev"\n')
        before = self.snapshot()
        with self.assertRaisesRegex(REFUSED, "foreign-pg.*0.4.1-dev"):
            BUMP(self.root, "0.5.0", "0.6.0-dev", write=False)
        self.assertEqual(self.snapshot(), before)

    def test_a_missing_member_and_a_rewritten_layout_are_refused(self):
        self.write("crates/kronik-blob/Cargo.toml", '[package]\nname = "kronik-blob"\nversion.workspace = true\n')
        with self.assertRaisesRegex(REFUSED, "no kronik-blob"):
            BUMP(self.root, "0.5.0", "0.6.0-dev", write=False)
        shutil.rmtree(self.root / "crates/kronik-blob")
        self.write("sdk/ts/package.json", json.dumps({"name": "@kronik/sdk", "version": "0.5.0"}))
        with self.assertRaisesRegex(REFUSED, "layout"):
            BUMP(self.root, "0.5.0", "0.6.0-dev", write=False)

    def test_the_repository_has_one_version_everywhere(self):
        version = WORKSPACE_VERSION(ROOT)
        BUMP(ROOT, version, version, write=False)


if __name__ == "__main__":
    unittest.main()
