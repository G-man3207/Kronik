SCHEMA = "kronik.fleet-enrollment/v1"
CAP = 1_048_576
TUNNEL_CHUNK_BYTES = 64 << 10
MAX_EVENT_FRAME = (1 << 20) + 2 * 525568 + 8192


def encoded(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def digest(value):
    return hashlib.sha256(value).hexdigest()


def openssl_environment():
    environment = {"PATH": "/usr/bin:/bin"}
    # The read-only host /usr supplies this symlink, not its /etc target. Check
    # inside this owned container; never modify or mount host OpenSSL settings.
    if not os.path.isfile("/usr/lib/ssl/openssl.cnf"):
        environment["OPENSSL_CONF"] = "/dev/null"
    return environment


def openssl_error_code(stderr):
    # Only this fixed code leaves the anonymous stderr file; no paths, subjects,
    # key material, tool messages or unrecognized bytes are copied to observations.
    message = stderr[:8192].lower()
    if b"openssl.cnf" in message and (b"no such file" in message or b"can't open" in message):
        return "OPENSSL_CONFIG_MISSING"
    if b"self-signature verify failure" in message or b"signature verification failure" in message:
        return "OPENSSL_CSR_SIGNATURE_INVALID"
    if b"unable to load provider" in message or b"unsupported" in message:
        return "OPENSSL_ALGORITHM_UNAVAILABLE"
    if b"asn1 encoding routines" in message or b"unable to load x509 request" in message:
        return "OPENSSL_ASN1_INVALID"
    if b"permission denied" in message or b"read-only file system" in message:
        return "OPENSSL_FILE_ACCESS"
    return "OPENSSL_EXECUTION_FAILED"


class DiagnosticTests(unittest.TestCase):
    def test_missing_guest_default_config_uses_empty_fixture_config(self):
        with mock.patch.object(os.path, "isfile", return_value=False) as exists:
            self.assertEqual(openssl_environment(),
                             {"PATH": "/usr/bin:/bin", "OPENSSL_CONF": "/dev/null"})
            exists.assert_called_once_with("/usr/lib/ssl/openssl.cnf")

    def test_existing_guest_default_config_is_not_overridden(self):
        with mock.patch.object(os.path, "isfile", return_value=True):
            self.assertEqual(openssl_environment(), {"PATH": "/usr/bin:/bin"})

    def test_diagnostics_are_fixed_codes_and_bounded(self):
        self.assertEqual(openssl_error_code(b"Can't open /usr/lib/ssl/openssl.cnf: No such file"),
                         "OPENSSL_CONFIG_MISSING")
        self.assertEqual(openssl_error_code(b"Certificate request self-signature verify failure"),
                         "OPENSSL_CSR_SIGNATURE_INVALID")
        self.assertEqual(openssl_error_code(b"private-credential unknown-tool-output"),
                         "OPENSSL_EXECUTION_FAILED")
        self.assertEqual(openssl_error_code(b"x" * 8192 + b" openssl.cnf: No such file"),
                         "OPENSSL_EXECUTION_FAILED")


def protected(path, cap=262144):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        info = os.fstat(fd)
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
                or info.st_mode & 0o077 or info.st_nlink != 1 or info.st_size > cap):
            raise ValueError("fixture file must be owner-only, regular and bounded")
        data = os.read(fd, cap + 1)
        if len(data) != info.st_size:
            raise ValueError("fixture file changed or exceeded bound")
        return data
    finally:
        os.close(fd)

class TunnelReader(io.RawIOBase):
    def __init__(self, tunnel):
        super().__init__()
        self.tunnel = tunnel

    def readable(self):
        return True

    def readinto(self, buffer):
        data = self.tunnel.recv(len(buffer))
        buffer[:len(data)] = data
        return len(data)


class TunnelSocket:
    """Socket-shaped byte stream for the standard-library HTTP client."""
    def __init__(self, handler):
        self.handler = handler
        self.buffer = bytearray()
        self.closed = False

    def sendall(self, data):
        for offset in range(0, len(data), TUNNEL_CHUNK_BYTES):
            self.handler.frame(2, data[offset:offset + TUNNEL_CHUNK_BYTES])

    def recv(self, length):
        if length == 0:
            return b""
        while not self.buffer and not self.closed:
            try:
                self.buffer.extend(self.handler.receive())
            except ValueError:
                self.closed = True
        data = bytes(self.buffer[:length])
        del self.buffer[:length]
        return data

    def makefile(self, mode, buffering=None):
        if mode != "rb":
            raise ValueError("HTTP tunnel requires a binary reader")
        return io.BufferedReader(TunnelReader(self))

    def close(self):
        self.closed = True


class TunnelHTTP(http.client.HTTPConnection):
    def __init__(self, tunnel):
        super().__init__("installation", timeout=30)
        self.tunnel = tunnel

    def connect(self):
        self.sock = self.tunnel



class Controller(http.server.ThreadingHTTPServer):
    daemon_threads = True
    request_queue_size = 4

    def __init__(self, args):
        self.args = args
        self.lock = threading.Lock()
        self.slots = threading.BoundedSemaphore(4)
        protected(args.issuer_key)
        self.token_hash = digest(protected(args.token_file).strip())
        self.plan = json.loads(protected(args.plan))
        self.rogue_bearer = protected(args.rogue_token_file, 4096).decode("ascii").strip() if args.rogue_token_file else None
        self.state = {"used_token_hashes": [], "admissions": {}}
        if os.path.exists(args.state):
            self.state = json.loads(protected(args.state, CAP))
        super().__init__((args.host, args.port), Handler)
        tls = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        tls.minimum_version = ssl.TLSVersion.TLSv1_2
        tls.load_cert_chain(args.cert, args.key)
        tls.load_verify_locations(cafile=args.client_ca)
        # Bootstrap is server-authenticated TLS; /v1/control requires its issued leaf.
        tls.verify_mode = ssl.CERT_OPTIONAL
        self.tls = tls

    def get_request(self):
        connection, peer = super().get_request()
        connection.settimeout(10)
        try:
            return self.tls.wrap_socket(connection, server_side=True), peer
        except (OSError, ssl.SSLError) as error:
            reasons = {
                "TLSV1_ALERT_UNKNOWN_CA", "SSLV3_ALERT_BAD_CERTIFICATE",
                "CERTIFICATE_VERIFY_FAILED", "UNEXPECTED_EOF_WHILE_READING",
                "PEER_DID_NOT_RETURN_A_CERTIFICATE", "TLSV1_ALERT_CERTIFICATE_REQUIRED",
                "TLSV1_ALERT_INTERNAL_ERROR",
            }
            reason = getattr(error, "reason", None)
            code = reason if reason in reasons else "TLS_HANDSHAKE_FAILED"
            if isinstance(error, TimeoutError):
                code = "TLS_HANDSHAKE_TIMEOUT"
            try:
                self.observe("tls_failure", code=code, peer_ip=peer[0])
            finally:
                connection.close()
            raise

    def observe(self, event, **fields):
        if not self.args.observations:
            return
        payload = encoded({"event": event, **fields}) + b"\n"
        fd = os.open(self.args.observations, os.O_WRONLY | os.O_APPEND | os.O_CREAT | os.O_NOFOLLOW, 0o600)
        try:
            info = os.fstat(fd)
            if not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid() or info.st_mode & 0o077 or info.st_nlink != 1:
                raise ValueError("observations file custody")
            os.write(fd, payload)
            os.fsync(fd)
        finally:
            os.close(fd)

    def process_request(self, request, client_address):
        self.slots.acquire()
        try:
            super().process_request(request, client_address)
        except BaseException:
            self.slots.release()
            raise

    def process_request_thread(self, request, client_address):
        try:
            super().process_request_thread(request, client_address)
        finally:
            self.slots.release()

    def commit(self):
        directory = os.path.dirname(os.path.abspath(self.args.state))
        fd, path = tempfile.mkstemp(prefix=".fleet-controller-", dir=directory)
        try:
            with os.fdopen(fd, "wb") as target:
                target.write(encoded(self.state))
                target.flush()
                os.fsync(target.fileno())
            os.replace(path, self.args.state)
            parent = os.open(directory, os.O_RDONLY | os.O_DIRECTORY)
            try:
                os.fsync(parent)
            finally:
                os.close(parent)
        finally:
            if os.path.exists(path):
                os.unlink(path)

    def issue(self, request):
        environment = openssl_environment()
        self.observe("issuer_environment",
                     code="DEFAULT_CONFIG_MISSING" if "OPENSSL_CONF" in environment else "DEFAULT_CONFIG_PRESENT")
        with tempfile.TemporaryDirectory(prefix="fleet-controller-csr-") as directory:
            csr_path = os.path.join(directory, "request.der")
            extensions = os.path.join(directory, "extensions")
            with open(csr_path, "wb") as target:
                target.write(bytes(request["csr_der"]))
            def openssl(stage, *arguments):
                self.observe("issuer_step", code=stage)
                # Anonymous private scratch is closed and removed immediately;
                # stderr is never inherited by the controller or retained in logs.
                with tempfile.TemporaryFile(dir=directory) as errors:
                    try:
                        result = subprocess.run(
                            ["/usr/bin/openssl", *arguments], cwd=directory,
                            env=environment, stdin=subprocess.DEVNULL,
                            stdout=subprocess.PIPE, stderr=errors,
                            timeout=5, check=True,
                        )
                        if len(result.stdout) > 65536:
                            raise ValueError("oversized certificate tool response")
                    except (ValueError, OSError, subprocess.SubprocessError) as error:
                        errors.seek(0)
                        self.observe("issuer_tool_error", code=openssl_error_code(errors.read(8192)))
                        self.observe("issuer_failure", code=stage,
                                     exit_code=error.returncode if isinstance(error, subprocess.CalledProcessError) else None)
                        raise
                return result.stdout
            openssl("CSR_SIGNATURE", "req", "-verify", "-inform", "DER", "-in", csr_path, "-noout")
            public = openssl("CSR_PUBLIC_KEY", "req", "-inform", "DER", "-in", csr_path, "-pubkey", "-noout")
            public_path = os.path.join(directory, "public.pem")
            with open(public_path, "wb") as target:
                target.write(public)
            spki = openssl("CSR_SPKI", "pkey", "-pubin", "-in", public_path, "-outform", "DER")
            if digest(spki) != request["client_key_sha256"]:
                self.observe("issuer_failure", code="CSR_KEY_BINDING")
                raise ValueError("CSR identity fingerprint")
            identity = request["plan"]["identity"]
            subject = "/CN=" + identity["installation"]
            if identity["cluster"] is not None:
                subject += "/O=" + identity["cluster"]
            if identity["node"] is not None:
                subject += "/OU=" + identity["node"]
            binding = "urn:kronik:fleet:request:" + request["request_id"] + ":" + str(request["epoch"])
            if self.args.wrong_client_binding:
                binding += ":wrong"
            with open(extensions, "w", encoding="ascii") as target:
                target.write("basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\nsubjectAltName=URI:" + binding + "\n")
            return openssl(
                "LEAF_SIGNING", "x509", "-req", "-inform", "DER", "-in", csr_path,
                "-CA", os.path.abspath(self.args.client_ca),
                "-CAkey", os.path.abspath(self.args.issuer_key),
                "-set_serial", "0x" + request["request_id"][:32], "-days", "1",
                "-subj", subject, "-extfile", extensions, "-outform", "DER",
            )


class Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def setup(self):
        super().setup()
        self.connection.settimeout(30)

    def log_message(self, *_):
        pass  # Credentials and request bodies never reach fixture logs.

    def reply(self, status, value):
        body = encoded(value)
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Connection", "close")
        self.end_headers()
        self.wfile.write(body)
        self.close_connection = True

    def do_POST(self):
        if self.path != "/v1/enroll":
            return self.reply(404, {"error": "not found"})
        self.server.observe("enrollment_http_start", peer_ip=self.client_address[0])
        stage = "TRANSFER_ENCODING"
        try:
            if self.headers.get("Transfer-Encoding") is not None:
                raise ValueError()
            stage = "BODY_LENGTH"
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= 65536:
                raise ValueError()
            stage = "BODY_READ"
            raw = self.rfile.read(length)
            if len(raw) != length:
                raise ValueError()
            stage = "JSON_DECODE"
            request = json.loads(raw)
            stage = "SCHEMA_FIELDS"
            if not isinstance(request, dict) or set(request) != {"schema", "request_id", "epoch", "plan", "api_bearer", "csr_der", "client_key_sha256"}:
                raise ValueError()
            stage = "SCHEMA_VERSION"
            if request["schema"] != SCHEMA:
                raise ValueError()
            stage = "PLAN_BINDING"
            if request["plan"] != self.server.plan:
                actual = request["plan"] if isinstance(request["plan"], dict) else {}
                fields = [name for name in ("controller_url", "identity", "scopes", "ca_sha256")
                          if actual.get(name) != self.server.plan.get(name)]
                self.server.observe("enrollment_plan_mismatch", fields=fields)
                raise ValueError()
            stage = "REQUEST_ID"
            request_id = request["request_id"]
            if (not isinstance(request_id, str) or len(request_id) != 64
                    or any(c not in "0123456789abcdef" for c in request_id)):
                raise ValueError()
            stage = "EPOCH"
            if type(request["epoch"]) is not int or request["epoch"] <= 0:
                raise ValueError()
            stage = "BEARER_FORMAT"
            if not isinstance(request["api_bearer"], str) or not 0 < len(request["api_bearer"]) <= 4096:
                raise ValueError()
            stage = "CSR_FORMAT"
            csr = bytes(request["csr_der"])
            if not 0 < len(csr) <= 16384 or len(request["client_key_sha256"]) != 64:
                raise ValueError()
        except (ValueError, TypeError, KeyError):
            self.server.observe("enrollment_rejected", code=stage, status=400)
            return self.reply(400, {"error": "invalid enrollment"})
        with self.server.lock:
            existing = self.server.state["admissions"].get(request_id)
            authorization = self.headers.get("Authorization")
            fingerprint = digest(encoded(request))
            self.server.observe("enrollment_request", request_id=request_id, epoch=request["epoch"],
                                csr_sha256=digest(csr), credential_present=authorization is not None,
                                peer_ip=self.client_address[0])
            if existing:
                if authorization is not None or existing["fingerprint"] != fingerprint:
                    self.server.observe("enrollment_rejected", code="RETRY_BINDING", status=409)
                    return self.reply(409, {"error": "request identity conflict"})
                return self.reply(200, existing["response"])
            if (self.server.token_hash in self.server.state["used_token_hashes"] or authorization is None
                    or not authorization.startswith("Bearer ")
                    or not hmac.compare_digest(digest(authorization[7:].encode()), self.server.token_hash)):
                self.server.observe("enrollment_rejected", code="INITIAL_CREDENTIAL", status=401)
                return self.reply(401, {"error": "initial credential required"})
            try:
                certificate = self.server.issue(request)
            except (ValueError, OSError, subprocess.SubprocessError):
                self.server.observe("enrollment_rejected", code="CSR_ISSUANCE", status=400)
                return self.reply(400, {"error": "invalid CSR"})
            response = {key: request[key] for key in ("schema", "request_id", "epoch", "plan")}
            response["controller_id"] = request["plan"]["ca_sha256"]
            response["client_cert_der"] = list(certificate)
            self.server.state["admissions"][request_id] = {
                "fingerprint": fingerprint, "peer": digest(certificate), "response": response,
                "bearer_hash": digest(request["api_bearer"].encode()),
            }
            self.server.state["used_token_hashes"].append(self.server.token_hash)
            self.server.commit()
            self.server.observe("enrollment_admitted", request_id=request_id)
            if self.server.args.lost_reply_once:
                self.server.observe("enrollment_reply_lost", request_id=request_id)
                self.close_connection = True
                self.connection.shutdown(socket.SHUT_RDWR)
                return
            self.reply(200, response)

    def do_GET(self):
        if self.path != "/v1/control":
            return self.reply(404, {"error": "not found"})
        authorization = self.headers.get("Authorization", "")
        request_id = self.headers.get("X-Kronik-Enrollment", "")
        with self.server.lock:
            admission = self.server.state["admissions"].get(request_id)
        if (not admission or not authorization.startswith("Bearer ")
                or not hmac.compare_digest(digest(authorization[7:].encode()), admission["bearer_hash"])
                or digest(self.connection.getpeercert(binary_form=True) or b"") != admission["peer"]
                or self.headers.get("X-Kronik-Epoch") != str(admission["response"]["epoch"])):
            return self.reply(403, {"error": "control identity"})
        try:
            key = self.headers.get("Sec-WebSocket-Key", "")
            if (self.headers.get("Upgrade", "").lower() != "websocket"
                    or "upgrade" not in self.headers.get("Connection", "").lower().split(", ")
                    or self.headers.get("Sec-WebSocket-Version") != "13"
                    or len(base64.b64decode(key, validate=True)) != 16):
                raise ValueError()
        except ValueError:
            return self.reply(400, {"error": "websocket handshake"})
        with self.server.lock:
            stage = admission.get("stage", 0)
            admission["stage"] = stage + 1
            self.server.commit()
        accept = base64.b64encode(hashlib.sha1((key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode()).digest()).decode()
        self.send_response(101)
        self.send_header("Upgrade", "websocket")
        self.send_header("Connection", "Upgrade")
        self.send_header("Sec-WebSocket-Accept", accept)
        self.end_headers()
        self.wfile.flush()
        self.server.observe("stream_open", request_id=request_id, epoch=admission["response"]["epoch"],
                            peer_ip=self.client_address[0])
        close_reason = "fixture_finished"
        tunnel = TunnelSocket(self)
        client = TunnelHTTP(tunnel)
        try:
            headers = {}
            if self.server.rogue_bearer:
                headers = {"Authorization": "Bearer " + self.server.rogue_bearer,
                           "Proxy-Authorization": "Bearer " + self.server.rogue_bearer,
                           "Cookie": "kronik_session=" + self.server.rogue_bearer}
            admin = "admin" in admission["response"]["plan"]["scopes"]
            if stage == 0:
                for path in ("/v1/health", "/v1/tokens"):
                    self.http_result(client, path, headers, request_id)
                if not admin:
                    self.http_result(client, "/v1/events/stream", headers, request_id, deny_stream=True)
                    self.http_result(client, "/v1/events/ws", self.websocket_headers(headers)[0], request_id, deny_stream=True)
                else:
                    self.sse(client, headers, admission, request_id)
                    close_reason = "fixture_reconnect"
                    self.frame(8, struct.pack("!H", 1000))
                    return
            if admin:
                self.inner_websocket(client, tunnel, headers, admission, request_id)
            elif self.server.args.hold_open:
                self.connection.settimeout(120)
                while tunnel.recv(1):
                    raise ValueError("unsolicited HTTP response bytes")
                close_reason = "peer_closed"
            self.frame(8, struct.pack("!H", 1000))
        except socket.timeout:
            close_reason = "timeout"
        except (OSError, ValueError, KeyError, TypeError, StopIteration, http.client.HTTPException):
            close_reason = "peer_closed"
        finally:
            client.close()
            self.close_connection = True
            self.server.observe("stream_closed", request_id=request_id, reason=close_reason)

    def http_result(self, client, path, headers, request_id, deny_stream=False):
        self.server.observe("http_request", request_id=request_id, method="GET", path=path)
        client.request("GET", path, headers=headers)
        response = client.getresponse()
        if deny_stream and response.status in (200, 101):
            self.server.observe("http_result", request_id=request_id, path=path,
                                status=response.status, body_sha256=digest(b""))
            raise ValueError("stream scope expanded")
        body = response.read(CAP + 1)
        if len(body) > CAP:
            raise ValueError("owned HTTP observation bound")
        self.server.observe("http_result", request_id=request_id, path=path,
                            status=response.status, body_sha256=digest(body))

    @staticmethod
    def websocket_headers(headers):
        key = base64.b64encode(os.urandom(16)).decode("ascii")
        return {**headers, "Upgrade": "websocket", "Connection": "Upgrade",
                "Sec-WebSocket-Version": "13", "Sec-WebSocket-Key": key}, key

    def sse(self, client, headers, admission, request_id):
        client.request("GET", "/v1/events/stream", headers=headers)
        response = client.getresponse()
        self.server.observe("sse_http", request_id=request_id, status=response.status)
        if response.status != 200 or response.getheader("Content-Type") != "text/event-stream":
            raise ValueError("native SSE admission failed")
        for _ in range(64):
            frame = bytearray()
            while True:
                line = response.readline(MAX_EVENT_FRAME + 1)
                if not line or len(frame) + len(line) > MAX_EVENT_FRAME:
                    raise ValueError("native SSE frame bound")
                frame.extend(line)
                if line in (b"\n", b"\r\n"):
                    break
            lines = bytes(frame).splitlines()
            if b"event: operational" not in lines:
                continue
            cursor = next(line[4:].lstrip().decode("utf-8") for line in lines if line.startswith(b"id:"))
            body = next(line[5:].lstrip() for line in lines if line.startswith(b"data:"))
            event = json.loads(body)
            if event.get("schema") != "kronik.event/v1":
                raise ValueError("native SSE schema")
            with self.server.lock:
                admission["cursor"] = cursor
                self.server.commit()
            self.server.observe("sse_event", request_id=request_id, event_id=event["id"], body_sha256=digest(body))
            return
        raise ValueError("no actual operational SSE event")

    def inner_websocket(self, client, tunnel, headers, admission, request_id):
        headers, key = self.websocket_headers(headers)
        if admission.get("cursor"):
            headers["Last-Event-ID"] = admission["cursor"]
        client.request("GET", "/v1/events/ws", headers=headers)
        response = client.getresponse()
        self.server.observe("ws_http", request_id=request_id, status=response.status)
        accept = base64.b64encode(hashlib.sha1((key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode()).digest()).decode()
        if response.status != 101 or response.getheader("Sec-WebSocket-Accept") != accept:
            raise ValueError("native WebSocket admission failed")
        source = response.fp
        if source is None:
            raise ValueError("native WebSocket upgrade closed")
        nonce = b"fleet-inner-ping"
        self.inner_send(tunnel, 9, nonce)
        saw_event = saw_pong = False
        for _ in range(128):
            opcode, payload = self.inner_receive(source)
            if opcode == 10 and payload == nonce:
                saw_pong = True
                self.server.observe("ws_pong", request_id=request_id)
            elif opcode == 1:
                event = json.loads(payload)
                if event.get("schema") == "kronik.event/v1":
                    saw_event = True
                    self.server.observe("ws_event", request_id=request_id, event_id=event["id"], body_sha256=digest(payload))
            elif opcode == 9:
                self.inner_send(tunnel, 10, payload)
            if saw_event and saw_pong:
                break
        if not saw_event or not saw_pong:
            raise ValueError("native WebSocket did not exchange actual event and pong")
        if self.server.args.hold_open:
            self.connection.settimeout(120)
            while True:
                opcode, payload = self.inner_receive(source)
                if opcode == 9:
                    self.inner_send(tunnel, 10, payload)
        self.inner_send(tunnel, 8, struct.pack("!H", 1000))

    @staticmethod
    def inner_send(tunnel, opcode, payload):
        if len(payload) > 125:
            raise ValueError("owned WebSocket control frame bound")
        mask = os.urandom(4)
        masked = bytes(value ^ mask[index % 4] for index, value in enumerate(payload))
        tunnel.sendall(bytes([0x80 | opcode, 0x80 | len(payload)]) + mask + masked)

    @staticmethod
    def inner_receive(source):
        def exact(length):
            data = source.read(length)
            if len(data) != length:
                raise ValueError("native WebSocket closed")
            return data
        first, second = exact(2)
        if first & 0x70 or not first & 0x80 or second & 0x80:
            raise ValueError("native WebSocket frame")
        opcode, length = first & 15, second & 127
        if length == 126:
            length = struct.unpack("!H", exact(2))[0]
        elif length == 127:
            length = struct.unpack("!Q", exact(8))[0]
        if length > MAX_EVENT_FRAME or (opcode >= 8 and length > 125):
            raise ValueError("native WebSocket frame bound")
        payload = exact(length)
        if opcode == 8:
            raise ValueError("native WebSocket closed")
        return opcode, payload

    def frame(self, opcode, payload):
        if len(payload) > TUNNEL_CHUNK_BYTES:
            raise ValueError("frame too large")
        prefix = bytes([0x80 | opcode])
        if len(payload) < 126:
            prefix += bytes([len(payload)])
        elif len(payload) <= 65535:
            prefix += b"\x7e" + struct.pack("!H", len(payload))
        else:
            prefix += b"\x7f" + struct.pack("!Q", len(payload))
        self.wfile.write(prefix + payload)
        self.wfile.flush()

    def exact(self, length):
        value = self.rfile.read(length)
        if len(value) != length:
            raise ValueError("truncated websocket frame")
        return value

    def receive(self):
        while True:
            first, second = self.exact(2)
            if first & 0x70 or not first & 0x80 or not second & 0x80:
                raise ValueError("unsupported websocket frame")
            opcode, length = first & 15, second & 127
            if length == 126:
                length = struct.unpack("!H", self.exact(2))[0]
            elif length == 127:
                length = struct.unpack("!Q", self.exact(8))[0]
            if length > TUNNEL_CHUNK_BYTES or (opcode >= 8 and length > 125):
                raise ValueError("websocket size bound")
            mask = self.exact(4)
            payload = bytes(value ^ mask[i % 4] for i, value in enumerate(self.exact(length)))
            if opcode == 9:
                self.frame(10, payload)
            elif opcode == 2:
                return payload
            else:
                raise ValueError("unexpected websocket control frame")


