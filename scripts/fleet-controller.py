#!/usr/bin/env python3
"""Owned loopback M29 protocol fixture, not a production control panel.

Supply existing server identity and realm CA/issuer key, protected one-time token
file and expected EnrollmentPlan JSON. Only client leaves are issued; no roots
or client private keys are generated by this controller.
Admissions survive restart; --lost-reply-once drops the first admitted response.
Control uses standard HTTP/1, SSE and an inner WebSocket over the outbound WSS
byte pipe. Observations contain public IDs, statuses, body digests and fixed
diagnostic phase/error codes, never credentials, tool stderr or request bodies.
"""
