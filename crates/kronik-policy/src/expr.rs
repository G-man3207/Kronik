//! One rule's `when`: compiled once, evaluated against many diffs.

use crate::json;
use cel::common::ast::{Expr as Node, IdedExpr};
use cel::common::types::CelBool;
use cel::{Context, Env, ParseErrors, Value};
use std::panic::{self, AssertUnwindSafe};
use std::sync::{Arc, LazyLock};

/// The longest accepted `when`, in bytes.
///
/// Parsing recurses for every link of a left-nested chain such as
/// `1 + 1 + …` or `a.b.c…`, one per two bytes: this bounds that recursion
/// (ADR 0007).
pub const MAX_WHEN_BYTES: usize = 1024;

/// The most levels a `when` may nest parentheses, brackets, braces, call
/// arguments and conditionals (`a ? b : c`) below its top level.
///
/// The parser, generated by ANTLR, takes about 6.5 KiB of stack per level in
/// release builds and 160 KiB in debug builds. With this bound and
/// [`MAX_WHEN_BYTES`], any input parses within 2 MiB of stack, the stack of a
/// tokio worker or test thread, in debug builds too (ADR 0007).
pub const MAX_WHEN_NESTING: usize = PARSER_RECURSION_LIMIT as usize;

const PARSER_RECURSION_LIMIT: u16 = 8;

/// The deepest accepted expression tree, where a comprehension (`exists`,
/// `all`, `exists_one`, `filter`, `map`) adds two levels.
///
/// Evaluation recurses once per level of the tree: at this bound it takes
/// about 64 KiB of stack in release builds and 1.3 MiB in debug builds
/// (ADR 0007).
pub const MAX_WHEN_DEPTH: usize = 32;

/// The CEL standard library and macros, without the optional-value syntax
/// (an extension, which cel-go leaves off by default too).
static ENV: LazyLock<Arc<Env>> =
    LazyLock::new(|| Arc::new(Env::stdlib().with_optional_support(false)));

/// A compiled `when` expression.
#[derive(Debug)]
pub(crate) struct Expr {
    ast: IdedExpr,
}

impl Expr {
    /// Parses `source` and checks the limits. The message of an error is
    /// meant to follow "invalid `when`: ".
    pub(crate) fn compile(source: &str) -> Result<Self, String> {
        if source.len() > MAX_WHEN_BYTES {
            return Err(format!(
                "the expression is {} bytes long; at most {MAX_WHEN_BYTES} are allowed",
                source.len()
            ));
        }
        // The parser is a dependency's code: should it panic on some input,
        // `policy set` fails rather than the daemon. Nothing it touched is
        // used after a panic.
        let parser = ENV.parser().max_recursion_depth(PARSER_RECURSION_LIMIT);
        let parsed = panic::catch_unwind(AssertUnwindSafe(|| parser.parse(source)))
            .map_err(|_| "the CEL parser failed on this expression".to_owned())?;
        let ast = parsed.map_err(|errors| syntax_errors(&errors))?;
        check(&ast)?;
        Ok(Self { ast })
    }

    /// Evaluates the expression with `value` bound to the variable `var`
    /// (`diff` for rules, `guard` for guards). `Err` holds the reason it
    /// could not: a missing field, a type error, a result that is not a `bool`.
    pub(crate) fn eval(&self, var: &str, value: &serde_json::Value) -> Result<bool, String> {
        let mut context = Context::with_env(Arc::clone(&ENV));
        context.add_variable_as_val(var, json::to_val(value));
        // As in `compile`: a panic in the interpreter fails this rule only.
        panic::catch_unwind(AssertUnwindSafe(|| {
            let value = Value::resolve_val(&self.ast, &context).map_err(|e| e.to_string())?;
            match value.downcast_ref::<CelBool>() {
                Some(b) => Ok(*b.inner()),
                None => Err(format!(
                    "the expression evaluated to a {}, not a bool",
                    value.get_type().name()
                )),
            }
        }))
        .unwrap_or_else(|_| Err("the CEL interpreter failed on this expression".to_owned()))
    }

    /// The expression names the identifier `ident` (a variable, or a
    /// comprehension's own variable of that name). The tree is at most
    /// [`MAX_WHEN_DEPTH`] deep, checked by `compile`.
    pub(crate) fn mentions(&self, ident: &str) -> bool {
        let mut pending = vec![&self.ast];
        while let Some(node) = pending.pop() {
            match &node.expr {
                Node::Ident(name) if name == ident => return true,
                Node::Select(select) => pending.push(&select.operand),
                Node::Call(call) => {
                    pending.extend(call.target.iter().map(|target| &**target));
                    pending.extend(call.args.iter());
                }
                Node::List(list) => pending.extend(list.elements.iter()),
                Node::Comprehension(c) => pending.extend([
                    &c.iter_range,
                    &c.accu_init,
                    &c.loop_cond,
                    &c.loop_step,
                    &c.result,
                ]),
                _ => {}
            }
        }
        false
    }
}

/// The parser's errors on one line. `ParseError`'s own `Display` is not used:
/// it panics on a column above `u16::MAX`.
fn syntax_errors(errors: &ParseErrors) -> String {
    // The parser reports its recursion limit as an opaque syntax error.
    if errors
        .errors
        .iter()
        .any(|e| e.msg.contains("Recursion limit of"))
    {
        return format!(
            "the expression nests parentheses, brackets, braces, calls or conditionals \
             more than {MAX_WHEN_NESTING} levels deep"
        );
    }
    let messages: Vec<String> = errors
        .errors
        .iter()
        .map(|e| format!("{} at line {}, column {}", e.msg, e.pos.0, e.pos.1))
        .collect();
    if messages.is_empty() {
        "syntax error".to_owned()
    } else {
        messages.join("; ")
    }
}

/// Rejects what evaluation can't do deterministically or within the stack:
/// trees deeper than [`MAX_WHEN_DEPTH`], and map literals, which CEL iterates
/// in an unspecified order. Walks with an explicit stack, as the tree may be
/// too deep to recurse over.
fn check(root: &IdedExpr) -> Result<(), String> {
    let mut pending = vec![(root, 1)];
    while let Some((node, depth)) = pending.pop() {
        if depth > MAX_WHEN_DEPTH {
            return Err(format!(
                "the expression nests deeper than {MAX_WHEN_DEPTH} levels"
            ));
        }
        match &node.expr {
            Node::Literal(_) | Node::Ident(_) => {}
            Node::Select(select) => pending.push((&select.operand, depth + 1)),
            Node::Call(call) => {
                pending.extend(call.target.iter().map(|target| (&**target, depth + 1)));
                pending.extend(call.args.iter().map(|arg| (arg, depth + 1)));
            }
            Node::List(list) => {
                pending.extend(list.elements.iter().map(|element| (element, depth + 1)));
            }
            Node::Comprehension(comprehension) => pending.extend(
                [
                    &comprehension.iter_range,
                    &comprehension.accu_init,
                    &comprehension.loop_cond,
                    &comprehension.loop_step,
                    &comprehension.result,
                ]
                .map(|part| (part, depth + 2)),
            ),
            Node::Map(_) => {
                return Err("map literals are not supported: CEL leaves the order in \
                            which a map is iterated unspecified, and a policy must \
                            evaluate deterministically"
                    .to_owned());
            }
            Node::Struct(message) => {
                return Err(format!(
                    "message construction (`{}{{…}}`) is not supported",
                    message.type_name
                ));
            }
            Node::Unspecified => return Err("the expression is incomplete".to_owned()),
        }
    }
    Ok(())
}
